// Spike S2: start-up time of a Qt Quick shell that links OpenCASCADE.
// Logs milliseconds since OS process creation at: main() entry, QGuiApplication constructed,
// QML engine loaded, first frame swapped. Exits by itself right after the first frame.
//
//   --out <file>      append one result line (key=value pairs) to <file>
//   --loose <dir>     load <dir>/Main.qml from loose files instead of the compiled-in module
//   --use-occt        after the first frame, call into every OCCT toolkit and time it
//   --label <text>    copied into the result line
#define WIN32_LEAN_AND_MEAN
#ifndef NOMINMAX
#define NOMINMAX
#endif
#include <windows.h>
#include <psapi.h>

#include <QDir>
#include <QFile>
#include <QGuiApplication>
#include <QQmlApplicationEngine>
#include <QQuickStyle>
#include <QQuickWindow>
#include <QTextStream>
#include <QTimer>
#include <atomic>

#ifdef S2_QMLTC
#include "main.h" // generated by qmltc from Main.qml
#endif

#ifndef S2_NO_OCCT
int occtTouch();
#endif

static unsigned long long fileTimeTo64(const FILETIME& ft)
{
    return (static_cast<unsigned long long>(ft.dwHighDateTime) << 32) | ft.dwLowDateTime;
}

// Milliseconds since the OS created this process (includes loader time, DLL load and static initialisers).
static double msSinceProcessCreation()
{
    static const unsigned long long created = [] {
        FILETIME c, e, k, u;
        GetProcessTimes(GetCurrentProcess(), &c, &e, &k, &u);
        return fileTimeTo64(c);
    }();
    FILETIME now;
    GetSystemTimePreciseAsFileTime(&now);
    return static_cast<double>(fileTimeTo64(now) - created) / 10000.0;
}

struct ModuleCount {
    int total = 0;
    int occt = 0;
    int qt = 0;
};

static ModuleCount countModules()
{
    ModuleCount mc;
    HMODULE mods[2048];
    DWORD needed = 0;
    if (!K32EnumProcessModules(GetCurrentProcess(), mods, sizeof(mods), &needed))
        return mc;
    const int n = static_cast<int>(needed / sizeof(HMODULE));
    for (int i = 0; i < n && i < 2048; ++i) {
        wchar_t name[MAX_PATH];
        if (!K32GetModuleBaseNameW(GetCurrentProcess(), mods[i], name, MAX_PATH))
            continue;
        ++mc.total;
        if (name[0] == L'T' && name[1] == L'K')
            ++mc.occt;
        if (name[0] == L'Q' && name[1] == L't' && name[2] == L'6')
            ++mc.qt;
    }
    return mc;
}

static std::atomic<int> g_warnings{0};
static QtMessageHandler g_prevHandler = nullptr;
static void messageHandler(QtMsgType type, const QMessageLogContext& ctx, const QString& msg)
{
    if (type == QtWarningMsg || type == QtCriticalMsg || type == QtFatalMsg) {
        ++g_warnings;
        if (const QByteArray log = qgetenv("S2_WARNLOG"); !log.isEmpty()) {
            QFile f(QString::fromLocal8Bit(log));
            if (f.open(QIODevice::Append | QIODevice::Text))
                f.write(msg.toUtf8() + '\n');
        }
    }
    if (g_prevHandler)
        g_prevHandler(type, ctx, msg);
}

// Qt would put the QML disk cache and the RHI pipeline/shader cache under %LOCALAPPDATA%\<exe name>.
// The spike must not write outside its folder: the QML disk cache is redirected to <exe dir>/../s2cache/qml
// (unless the caller set QML_DISK_CACHE_PATH), and the RHI disk cache is switched off in main()
// (with Direct3D 11 Qt stored nothing in it: the folder stayed empty over 250 runs).
static void keepCachesInsideSpikeFolder()
{
    wchar_t buf[MAX_PATH];
    const DWORD n = GetModuleFileNameW(nullptr, buf, MAX_PATH);
    QString exe = QString::fromWCharArray(buf, static_cast<int>(n));
    exe.replace(QLatin1Char('\\'), QLatin1Char('/'));
    const QString dir = exe.left(exe.lastIndexOf(QLatin1Char('/')));
    const QString cache = dir.left(dir.lastIndexOf(QLatin1Char('/'))) + QStringLiteral("/s2cache");
    QDir().mkpath(cache + QStringLiteral("/qml"));
    if (!qEnvironmentVariableIsSet("QML_DISK_CACHE_PATH"))
        qputenv("QML_DISK_CACHE_PATH", (cache + QStringLiteral("/qml")).toLocal8Bit());
}

int main(int argc, char* argv[])
{
    const double tMain = msSinceProcessCreation();
    // Benchmark aid for a busy machine (other jobs running): raise our priority so their load distorts less.
    const bool highPriority = GetEnvironmentVariableW(L"S2_HIGH_PRIORITY", nullptr, 0) != 0;
    if (highPriority)
        SetPriorityClass(GetCurrentProcess(), HIGH_PRIORITY_CLASS);
    const ModuleCount modsAtMain = countModules();
    keepCachesInsideSpikeFolder();
    g_prevHandler = qInstallMessageHandler(messageHandler);

    QString outPath, looseDir, label = QStringLiteral("-");
    bool useOcct = false;
    for (int i = 1; i < argc; ++i) {
        const QString a = QString::fromLocal8Bit(argv[i]);
        if (a == QLatin1String("--out") && i + 1 < argc)
            outPath = QString::fromLocal8Bit(argv[++i]);
        else if (a == QLatin1String("--loose") && i + 1 < argc)
            looseDir = QString::fromLocal8Bit(argv[++i]);
        else if (a == QLatin1String("--label") && i + 1 < argc)
            label = QString::fromLocal8Bit(argv[++i]);
        else if (a == QLatin1String("--use-occt"))
            useOcct = true;
    }

    QCoreApplication::setAttribute(Qt::AA_DisableShaderDiskCache);
    QGuiApplication app(argc, argv);
    QQuickStyle::setStyle(QStringLiteral("Basic"));
    const double tApp = msSinceProcessCreation();

    QQmlApplicationEngine engine;
    const double tEngine = msSinceProcessCreation();
    QQuickWindow* window = nullptr;
#ifdef S2_QMLTC
    Main* root = new Main(&engine);
    window = root;
#else
    if (looseDir.isEmpty())
        engine.loadFromModule("RayShell", "Main");
    else
        engine.load(QUrl::fromLocalFile(QDir(looseDir).absoluteFilePath(QStringLiteral("Main.qml"))));
    if (engine.rootObjects().isEmpty())
        return 2;
    window = qobject_cast<QQuickWindow*>(engine.rootObjects().constFirst());
#endif
    if (!window)
        return 3;
    const double tQml = msSinceProcessCreation();

    std::atomic<double> tFrame{-1.0};
    std::atomic<bool> seen{false};
    // frameSwapped is emitted on the render thread: take the timestamp there, finish on the GUI thread.
    QObject::connect(
        window, &QQuickWindow::frameSwapped, window,
        [&] {
            if (!seen.exchange(true)) {
                tFrame = msSinceProcessCreation();
                QMetaObject::invokeMethod(
                    &app,
                    [&] {
                        const ModuleCount modsAtFrame = countModules();
                        double occtMs = -1.0;
                        int occtResult = -1;
                        ModuleCount modsAfterOcct = modsAtFrame;
#ifndef S2_NO_OCCT
                        if (useOcct) {
                            const double t0 = msSinceProcessCreation();
                            occtResult = occtTouch();
                            occtMs = msSinceProcessCreation() - t0;
                            modsAfterOcct = countModules();
                        }
#else
                        Q_UNUSED(useOcct);
#endif
                        const QString line =
                            QStringLiteral("label=%1 main_ms=%2 app_ms=%3 engine_ms=%16 qml_ms=%4 frame_ms=%5 occt_use_ms=%6 "
                                           "occt_result=%7 mods_main=%8 occt_mods_main=%9 mods_frame=%10 "
                                           "occt_mods_frame=%11 occt_mods_after_use=%12 qt_mods_frame=%13 warnings=%14 "
                                           "backend=%15 high_priority=%17\n")
                                .arg(label)
                                .arg(tMain, 0, 'f', 2)
                                .arg(tApp, 0, 'f', 2)
                                .arg(tQml, 0, 'f', 2)
                                .arg(tFrame.load(), 0, 'f', 2)
                                .arg(occtMs, 0, 'f', 2)
                                .arg(occtResult)
                                .arg(modsAtMain.total)
                                .arg(modsAtMain.occt)
                                .arg(modsAtFrame.total)
                                .arg(modsAtFrame.occt)
                                .arg(modsAfterOcct.occt)
                                .arg(modsAtFrame.qt)
                                .arg(g_warnings.load())
                                .arg(static_cast<int>(QQuickWindow::graphicsApi()))
                                .arg(tEngine, 0, 'f', 2)
                                .arg(highPriority ? 1 : 0);
                        if (!outPath.isEmpty()) {
                            QFile f(outPath);
                            if (f.open(QIODevice::Append | QIODevice::Text))
                                f.write(line.toUtf8());
                        }
                        QTextStream(stdout) << line;
                        QCoreApplication::quit();
                    },
                    Qt::QueuedConnection);
            }
        },
        Qt::DirectConnection);

    // Safety net: never stay open on the user's desktop.
    QTimer::singleShot(30000, &app, [] { QCoreApplication::exit(4); });
    return app.exec();
}
