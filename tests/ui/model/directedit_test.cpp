// The vertical holes of an imported plate (cylinders about a vertical axis wholly inside its outline), lowest x first:
// each hole's wall faces (often two halves) and its radius.
struct Hole {
    Vec3 axis{};
    double radius = 0;
    std::vector<std::uint32_t> walls;
};
std::vector<Hole> holesOf(const std::vector<Face>& faces)
{
    Box3 box{{1e300, 1e300, 1e300}, {-1e300, -1e300, -1e300}};
    for (const Face& f : faces) {
        box.min = {std::min(box.min.x, f.s.bounds.min.x), std::min(box.min.y, f.s.bounds.min.y),
                   std::min(box.min.z, f.s.bounds.min.z)};
        box.max = {std::max(box.max.x, f.s.bounds.max.x), std::max(box.max.y, f.s.bounds.max.y),
                   std::max(box.max.z, f.s.bounds.max.z)};
    }
    std::vector<Hole> out;
    for (const Face& f : faces) {
        const kernel::SurfaceInfo& s = f.s;
        if (s.type != kernel::SurfaceType::Cylinder || std::abs(std::abs(s.axis.z) - 1) > 1e-9 ||
            s.origin.x - s.radius < box.min.x + 1e-3 || s.origin.x + s.radius > box.max.x - 1e-3 ||
            s.origin.y - s.radius < box.min.y + 1e-3 || s.origin.y + s.radius > box.max.y - 1e-3)
            continue;
        auto it = std::find_if(out.begin(), out.end(), [&](const Hole& h) {
            return std::abs(h.axis.x - s.origin.x) < 1e-6 && std::abs(h.axis.y - s.origin.y) < 1e-6;
        });
        if (it == out.end()) {
            out.push_back(Hole{s.origin, s.radius, {}});
            it = out.end() - 1;
        }
        it->walls.push_back(f.index);
    }
    std::sort(out.begin(), out.end(), [](const Hole& a, const Hole& b) { return a.axis.x < b.axis.x; });
    return out;
}

// The hole walls about (x, y) in a shape.
int wallsAt(const kernel::Shape& shape, Vec3 axis)
{
    int n = 0;
    JobContext ctx;
    for (std::uint32_t i = 0; i < shape.count(kernel::SubKind::Face); ++i) {
        auto info = api::viewer::describeElement(shape, kernel::SubId{kernel::SubKind::Face, i}, ctx);
        if (info && info->surface && info->surface->type == kernel::SurfaceType::Cylinder &&
            std::abs(std::abs(info->surface->axis.z) - 1) < 1e-9 && std::abs(info->surface->origin.x - axis.x) < 1e-6 &&
            std::abs(info->surface->origin.y - axis.y) < 1e-6)
            ++n;
    }
    return n;
}

// The planar face with the highest centroid (the top of a block lying on XY).
Face topFace(const std::vector<Face>& faces)
{
    std::optional<Face> top;
    for (const Face& f : faces) {
        if (f.s.type == kernel::SurfaceType::Plane && std::abs(std::abs(f.s.axis.z) - 1) < 1e-9 &&
            (!top || f.s.centroid.z > top->s.centroid.z))
            top = f;
    }
    REQUIRE(top.has_value());
    return *top;
}

const kernel::Shape& previewShape(const Window& w, const QString& body)
{
    const doc::BuildResultPtr build = w.document()->previewBuild();
    REQUIRE(build);
    const auto it = build->bodies.find(BodyId{Uuid::fromString(body.toStdString())});
    REQUIRE(it != build->bodies.end());
    return it->second.shape;
}

std::string refJson(const Window& w, std::uint32_t face, int body = 0)
{
    const QJsonObject args{{QStringLiteral("body"), w.bodyId(body)},
                           {QStringLiteral("kind"), QStringLiteral("face")},
                           {QStringLiteral("index"), static_cast<int>(face)}};
    const QJsonObject r = QJsonDocument::fromJson(
                              QByteArray::fromStdString(w.invokeResult(
                                  "model.reference", QJsonDocument(args).toJson(QJsonDocument::Compact).toStdString())))
                              .object();
    return QJsonDocument(r.value(QStringLiteral("ref")).toObject()).toJson(QJsonDocument::Compact).toStdString();
}

const doc::Feature& lastFeature(const Window& w)
{
    const doc::DocStatePtr state = w.document()->state();
    REQUIRE_FALSE(state->features.empty());
    static doc::Feature copy;
    copy = state->features.back();
    return copy;
}

std::optional<cam::OpStatus> opStatus(const Window& w, std::uint64_t n)
{
    const auto all = w.host->app()->cam()->status(w.document()->state(), w.document()->build());
    const auto it = all.find(ct::opId(n));
    return it == all.end() ? std::nullopt : std::optional<cam::OpStatus>(it->second.status);
}

// The row of the review panel whose reference is of this owner (and in this state), -1 if none.
int reviewRow(const Window& w, const std::string& ownerId, std::optional<naming::ResolveState> state = std::nullopt)
{
    for (int i = 0; i < w.review()->rows().size(); ++i) {
        const api::references::Reference* r = w.review()->referenceAt(i);
        if (r != nullptr && r->ownerId == ownerId && (!state || r->state == *state))
            return i;
    }
    return -1;
}

