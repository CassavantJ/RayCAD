// Sketch JSON for feature.sketch.add: rectangles (x0, y0, x1, y1) and circles (x, y, r), entity ids from `base` on.
std::string sketchJson(const std::vector<std::array<double, 4>>& rects,
                       const std::vector<std::array<double, 3>>& circles, int base)
{
    int n = base;
    std::vector<std::string> e;
    const auto id = [](int k) {
        return ct::id('e', static_cast<std::uint64_t>(k));
    };
    const auto pt = [&](double x, double y) {
        const int k = n++;
        e.push_back(R"({"id":")" + id(k) + R"(","type":"point","x":)" + std::to_string(x) + R"(,"y":)" +
                    std::to_string(y) + "}");
        return k;
    };
    for (const auto& r : rects) {
        const int p[4] = {pt(r[0], r[1]), pt(r[2], r[1]), pt(r[2], r[3]), pt(r[0], r[3])};
        for (int i = 0; i < 4; ++i) {
            const int k = n++;
            e.push_back(R"({"id":")" + id(k) + R"(","type":"line","a":")" + id(p[i]) + R"(","b":")" +
                        id(p[(i + 1) % 4]) + R"("})");
        }
    }
    for (const auto& c : circles) {
        const int centre = pt(c[0], c[1]);
        const int k = n++;
        e.push_back(R"({"id":")" + id(k) + R"(","type":"circle","center":")" + id(centre) + R"(","radius":)" +
                    std::to_string(c[2]) + "}");
    }
    std::string out = R"({"schema":1,"entities":[)";
    for (std::size_t i = 0; i < e.size(); ++i)
        out += (i == 0 ? "" : ",") + e[i];
    return out + R"(],"constraints":[]})";
}

