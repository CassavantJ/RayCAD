        w.previewed("warning");
        knob = w.shown(QStringLiteral("directEditHandle.distance"));
        drag(40, Qt::NoModifier);
        CHECK(distanceMm() > committed);
        CHECK(std::abs(distanceMm() / step - std::round(distanceMm() / step)) < 1e-6);
