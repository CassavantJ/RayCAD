// Acceptance of task T-077: a holder passing through the vise jaw raises HolderHitsFixture.
//
// A real document: a 100 x 60 x 20 block (body b) with a 60 x 20 pocket 12 deep near its front (-Y) side; the shipped
// vise (resources/library/fixtures/generic-vise-6in.step) imported with the role "fixture", its fixed jaw mated to the
// part's front face and lowered so the jaw stands 3 mm above the part's top, its moving jaw mated to the fixed jaw with
// the part's width as the gap (closed on the part). A pocket2d operation on the pocket floor with a 10 mm end mill held
// 14 mm out of a 30 mm holder, generated by the CAM engine. The program is built by the builder the simulator's
// callers share (ray_api/cam_sim.h, T-075: part, stock and fixtures as closed soups in the setup WCS) and checked by
// the safety checks
// (src/sim/verify.h). Along the pocket's front wall the holder overhangs the jaw, 1 mm below its top: HolderHitsFixture
// on fixture 1 (the vise), and ToolTooShort with the stick-out that clears it; nothing else. The twin: the same job
// with the vise 5 mm lower (the jaw 2 mm below the part's top), generated again: no event at all.
